/** The CG index the font draws for an unmapped EBCDIC byte: a solid box. */
export const CG_BOXSOLID = 0xdf;

/**
 * Translate one EBCDIC byte to its CG glyph index.
 *
 * Out-of-range input yields `CG_BOXSOLID` rather than throwing: this sits on the drawing
 * path, and a malformed byte from a host must show as a visible box, not crash a window.
 */
export function ebcdicToCg(ebcdic: number): number {
  return EBC2CG[ebcdic & 0xff] ?? CG_BOXSOLID;
}
